def render(density: tuple[str, ...] = DENSITY, chars: str = CHARS) -> str:
    lines: list[str] = []
    for row in density:
        line = "".join(chars[min(int(value), len(chars) - 1)] for value in row)
        lines.append(line.rstrip())
    width = max(len(line) for line in lines)
    return "\n".join(" " * ((width - len(line)) // 2) + line for line in lines)


def main() -> None:
    print(render())


